let host, root
beforeEach(() => {
  mocks.S = { unit: 'kg', theme: 'dark', accent: 'lime', workouts: [], routines: [], exWeights: {} }
  host = document.createElement('div')
  document.body.appendChild(host)
  root = createRoot(host)
})
afterEach(() => {
  act(() => root.unmount())
  host.remove()
})

describe('Settings look page', () => {
  it('shows the gym logo and no accent colour picker', () => {
    act(() => root.render(<Settings page="look" />))
    const logo = host.querySelector('img.gym-brand')
    expect(logo).toBeTruthy()
    expect(logo.getAttribute('alt')).toBe(brand.name)
    expect(host.textContent).toContain('Identidade visual da academia')
    expect(host.querySelector('.swatch, .swatch-own, input[type="color"]')).toBe(null)
    expect(host.textContent).not.toContain('Accent color')
  })

  it('does not offer the accent colour in settings search', () => {
    for (const q of ['accent', 'custom color', 'picker', 'hex']) {
      expect(searchSettings(q, {}).map(h => h.title), q).not.toContain('Accent color')
    }
  })
})
